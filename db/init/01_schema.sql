EXECUTE FUNCTION GEO.VALIDATE_TERRITORY ();

CREATE OR REPLACE FUNCTION GEO.RESOLVE_TERRITORY (P_POINT GEOGRAPHY) RETURNS UUID LANGUAGE SQL STABLE AS $$
 SELECT t.id FROM geo.territory t WHERE t.active AND t.boundary IS NOT NULL
 AND ST_Covers(t.boundary,p_point) ORDER BY
 CASE territory_type WHEN 'neighborhood' THEN 1 WHEN 'zone' THEN 2 WHEN 'municipality' THEN 3
 WHEN 'province' THEN 4 ELSE 5 END, ST_Area(t.boundary) LIMIT 1 $$;

