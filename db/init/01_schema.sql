CREATE OR REPLACE FUNCTION CATALOG.CHECK_CATEGORY_PARENT () RETURNS TRIGGER LANGUAGE PLPGSQL AS $$
BEGIN
 IF NEW.parent_id IS NULL THEN RETURN NEW; END IF;
	IF NOT EXISTS (SELECT 1 FROM catalog.category WHERE id=NEW.parent_id) THEN
		RAISE EXCEPTION 'Categoria padre inexistente';
	END IF;
 IF EXISTS (WITH RECURSIVE a AS (
		SELECT id,parent_id,ARRAY[id] AS visited FROM catalog.category WHERE id=NEW.parent_id
		UNION ALL SELECT c.id,c.parent_id,a.visited||c.id FROM catalog.category c JOIN a ON c.id=a.parent_id
		WHERE NOT c.id=ANY(a.visited)) SELECT 1 FROM a WHERE id=NEW.id) THEN
  RAISE EXCEPTION 'Ciclo de catalogo'; END IF;
 RETURN NEW;
END $$;

