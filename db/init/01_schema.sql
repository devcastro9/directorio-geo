-- Territorio boliviano. INE autoridad principal, OSM complementario.
-- Los poligonos se usan internamente para asignar/verificar ubicaciones.
-- El visitante selecciona zonas por nombre, no dibuja poligonos ni usa GIS.
CREATE TABLE GEO.TERRITORY (
	ID UUID PRIMARY KEY DEFAULT UUIDV7(),
	PARENT_ID UUID REFERENCES GEO.TERRITORY (ID),
	TERRITORY_TYPE VARCHAR(20) NOT NULL CHECK (
		TERRITORY_TYPE IN (
			'department',
			'province',
			'municipality',
			'zone',
			'neighborhood'
		)
	),
	CODE_INE VARCHAR(30),
	NAME VARCHAR(150) NOT NULL,
	SOURCE VARCHAR(20) NOT NULL DEFAULT 'INE' CHECK (SOURCE IN ('INE', 'OSM', 'MANUAL')),
	OSM_TYPE VARCHAR(30),
	OSM_ID BIGINT,
	SOURCE_VERSION VARCHAR(100),
	BOUNDARY GEOGRAPHY (MULTIPOLYGON, 4326),
	CENTROID GEOGRAPHY (POINT, 4326),
	ACTIVE BOOLEAN NOT NULL DEFAULT TRUE,
	CREATED_BY_USER_ID UUID DEFAULT APP.ACTOR(),
	UPDATED_BY_USER_ID UUID,
	DELETED_BY_USER_ID UUID,
	CREATED_AT TIMESTAMPTZ NOT NULL DEFAULT NOW(),
	UPDATED_AT TIMESTAMPTZ NOT NULL DEFAULT NOW(),
	DELETED_AT TIMESTAMPTZ,
	CHECK ((DELETED_AT IS NULL) = ACTIVE),
	CHECK (BTRIM(NAME) <> ''),
	CHECK (
		BOUNDARY IS NULL
		OR (
			ST_ISVALID (BOUNDARY::GEOMETRY)
			AND NOT ST_ISEMPTY (BOUNDARY::GEOMETRY)
		)
	),
	UNIQUE (TERRITORY_TYPE, CODE_INE),
	UNIQUE (OSM_TYPE, OSM_ID)
);

