CREATE OR REPLACE FUNCTION APP.VALIDATE_PHOTO_BYTES () RETURNS TRIGGER LANGUAGE PLPGSQL AS $$
DECLARE mx integer; sig text;
BEGIN
 IF TG_TABLE_NAME='branch_photo' THEN
  mx:=(catalog.get_parameter('photo.max_bytes','branch',NEW.branch_id)#>>'{}')::integer;
 ELSE
  mx:=catalog.param_int('photo.max_bytes');
 END IF;
 IF mx IS NOT NULL AND octet_length(NEW.photo_data)>mx THEN RAISE EXCEPTION 'Imagen excede % bytes',mx; END IF;
 sig := encode(substring(NEW.photo_data FROM 1 FOR 12),'hex');
 IF NOT ((NEW.mime_type='image/jpeg' AND left(sig,6)='ffd8ff') OR
  (NEW.mime_type='image/png' AND left(sig,16)='89504e470d0a1a0a') OR
  (NEW.mime_type='image/webp' AND left(sig,8)='52494646' AND substring(sig FROM 17 FOR 8)='57454250')) THEN
  RAISE EXCEPTION 'Firma de imagen no coincide con tipo MIME'; END IF;
 RETURN NEW;
END $$;

