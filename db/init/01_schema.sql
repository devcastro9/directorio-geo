AFTER INSERT OR UPDATE OF BUSINESS_ID, DELETED_AT ON APP.BRANCH
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION APP.CHECK_PUBLICATION_CATEGORIES();

