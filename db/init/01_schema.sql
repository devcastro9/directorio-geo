CREATE OR REPLACE FUNCTION GEO.VALIDATE_TERRITORY () RETURNS TRIGGER LANGUAGE PLPGSQL AS $$
DECLARE pt text;
BEGIN
 IF NEW.territory_type='department' AND NEW.parent_id IS NOT NULL THEN RAISE EXCEPTION 'Departamento sin padre'; END IF;
 IF NEW.territory_type<>'department' AND NEW.parent_id IS NULL THEN RAISE EXCEPTION 'Falta territorio padre'; END IF;
 IF NEW.parent_id IS NULL THEN RETURN NEW; END IF;
 SELECT territory_type INTO pt FROM geo.territory WHERE id=NEW.parent_id;
 IF NOT ((NEW.territory_type='province' AND pt='department') OR
         (NEW.territory_type='municipality' AND pt='province') OR
         (NEW.territory_type='zone' AND pt='municipality') OR
         (NEW.territory_type='neighborhood' AND pt IN ('municipality','zone'))) THEN
   RAISE EXCEPTION 'Jerarquia territorial invalida: % bajo %',NEW.territory_type,pt; END IF;
 IF EXISTS (WITH RECURSIVE a AS (
 SELECT id,parent_id,ARRAY[id] AS path FROM geo.territory WHERE id=NEW.parent_id
 UNION ALL SELECT t.id,t.parent_id,a.path||t.id FROM geo.territory t JOIN a ON t.id=a.parent_id WHERE NOT t.id=ANY(a.path)
 ) SELECT 1 FROM a WHERE id=NEW.id) THEN RAISE EXCEPTION 'Ciclo territorial'; END IF;
 RETURN NEW;
END $$;

CREATE TRIGGER TERRITORY_VALIDATE
BEFORE INSERT OR UPDATE OF PARENT_ID,
