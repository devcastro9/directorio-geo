-- Creacion y publicacion atomica; el backend autentica y verifica p_user_id antes de invocar.
CREATE OR REPLACE FUNCTION APP.CREATE_BUSINESS_WITH_BRANCH (
	P_USER_ID UUID,
	P_TRADE_NAME TEXT,
	P_BRANCH_NAME TEXT,
	P_ADDRESS TEXT,
	P_LON DOUBLE PRECISION,
	P_LAT DOUBLE PRECISION,
	P_DESCRIPTION TEXT DEFAULT NULL,
	P_TERRITORY_ID UUID DEFAULT NULL,
	P_CATEGORY_IDS UUID[] DEFAULT NULL
) RETURNS UUID LANGUAGE PLPGSQL AS $$
DECLARE bid uuid; sid uuid;
BEGIN
 IF p_user_id IS NULL THEN RAISE EXCEPTION 'Usuario requerido'; END IF;
 IF coalesce(cardinality(p_category_ids),0)=0 OR EXISTS (
  SELECT 1 FROM unnest(p_category_ids) x(id)
  WHERE NOT EXISTS (SELECT 1 FROM catalog.category c WHERE c.id=x.id AND c.active)
 ) THEN RAISE EXCEPTION 'Se requiere al menos una categoria vigente'; END IF;
 INSERT INTO app.business(trade_name,description,status,created_by_user_id)
 VALUES(p_trade_name,p_description,'published',p_user_id) RETURNING id INTO bid;
 INSERT INTO app.business_owner(business_id,user_id,created_by_user_id) VALUES(bid,p_user_id,p_user_id);
 INSERT INTO app.branch(business_id,name,address,location,territory_id,is_primary)
 VALUES(bid,p_branch_name,p_address,ST_SetSRID(ST_MakePoint(p_lon,p_lat),4326)::geography,p_territory_id,true) RETURNING id INTO sid;
 INSERT INTO app.branch_category(branch_id,category_id)
 SELECT sid,x.id FROM (SELECT DISTINCT unnest(p_category_ids) AS id) x;
 RETURN bid;
END $$;

CREATE OR REPLACE FUNCTION APP.SOFT_DELETE_BRANCH (P_BRANCH_ID UUID, P_ACTOR UUID) RETURNS VOID LANGUAGE PLPGSQL AS $$
BEGIN
 UPDATE app.branch SET status='permanently_closed',deleted_at=now(),deleted_by_user_id=p_actor,is_primary=false
 WHERE id=p_branch_id AND status IN ('active','temporarily_closed');
 -- Tambien se permite dar de baja la ultima sucursal.
END $$;

CREATE OR REPLACE FUNCTION APP.SOFT_DELETE_BUSINESS (P_BUSINESS_ID UUID, P_ACTOR UUID) RETURNS VOID LANGUAGE PLPGSQL AS $$
BEGIN
 UPDATE app.business SET deleted_at=now(),deleted_by_user_id=p_actor,status='archived'
 WHERE id=p_business_id AND status <> 'archived';
 UPDATE app.branch SET status='permanently_closed',deleted_at=coalesce(deleted_at,now()),deleted_by_user_id=coalesce(deleted_by_user_id,p_actor),is_primary=false
 WHERE business_id=p_business_id;
END $$;

