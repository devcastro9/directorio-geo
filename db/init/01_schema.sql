CREATE OR REPLACE FUNCTION APP.TOUCH () RETURNS TRIGGER LANGUAGE PLPGSQL AS $$
BEGIN
 NEW.updated_at:=clock_timestamp();
 NEW.updated_by_user_id:=coalesce(app.actor(),NEW.updated_by_user_id);
 IF NEW.deleted_at IS NOT NULL AND OLD.deleted_at IS NULL THEN
  NEW.deleted_by_user_id:=coalesce(NEW.deleted_by_user_id,app.actor());
 ELSIF NEW.deleted_at IS NULL AND OLD.deleted_at IS NOT NULL THEN
  NEW.deleted_by_user_id:=NULL;
 END IF;
 RETURN NEW;
END $$;

