CREATE EXTENSION IF NOT EXISTS postgis;
CREATE EXTENSION IF NOT EXISTS unaccent;
CREATE EXTENSION IF NOT EXISTS pg_trgm;
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- unaccent no es IMMUTABLE por defecto; este envoltorio permite usarlo
-- en columnas generadas e índices.
CREATE OR REPLACE FUNCTION f_unaccent(text) RETURNS text
LANGUAGE sql IMMUTABLE PARALLEL SAFE STRICT
AS $$ SELECT public.unaccent('public.unaccent'::regdictionary, $1) $$;

CREATE OR REPLACE FUNCTION set_actualizado_en() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.actualizado_en = now();
    RETURN NEW;
END $$;

-- ---------------------------------------------------------------------
-- Ciudades
-- ---------------------------------------------------------------------
CREATE TABLE ciudad (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(80)  NOT NULL,
    departamento  VARCHAR(40)  NOT NULL,
    slug          VARCHAR(100) NOT NULL UNIQUE,
    centro        GEOMETRY(Point, 4326),          -- para centrar el mapa
    activo        BOOLEAN      NOT NULL DEFAULT TRUE,
    UNIQUE (nombre, departamento)
);

-- ---------------------------------------------------------------------
-- Categorías y subcategorías (dos niveles)
-- ---------------------------------------------------------------------
CREATE TABLE categoria (
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    padre_id  INTEGER REFERENCES categoria(id) ON DELETE RESTRICT,
    nombre    VARCHAR(80)  NOT NULL,
    slug      VARCHAR(100) NOT NULL UNIQUE,
    orden     SMALLINT     NOT NULL DEFAULT 0,
    activo    BOOLEAN      NOT NULL DEFAULT TRUE,
    CHECK (padre_id IS NULL OR padre_id <> id)
);
CREATE INDEX categoria_padre_idx ON categoria (padre_id);

-- Garantiza que una subcategoría no tenga a su vez subcategorías.
CREATE OR REPLACE FUNCTION categoria_dos_niveles() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.padre_id IS NOT NULL AND EXISTS (
        SELECT 1 FROM categoria WHERE id = NEW.padre_id AND padre_id IS NOT NULL
    ) THEN
        RAISE EXCEPTION 'Solo se permiten dos niveles de categorías';
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER categoria_dos_niveles_trg
    BEFORE INSERT OR UPDATE ON categoria
    FOR EACH ROW EXECUTE FUNCTION categoria_dos_niveles();

-- ---------------------------------------------------------------------
-- Negocios
-- ---------------------------------------------------------------------
CREATE TABLE negocio (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         VARCHAR(150) NOT NULL,
    slug           VARCHAR(180) NOT NULL UNIQUE,
    descripcion    TEXT         NOT NULL DEFAULT '',
    ciudad_id      INTEGER      NOT NULL REFERENCES ciudad(id),
    direccion      VARCHAR(200) NOT NULL DEFAULT '',
    telefono       VARCHAR(30)  NOT NULL DEFAULT '',   -- teléfono comercial
    whatsapp       VARCHAR(30)  NOT NULL DEFAULT '',
    sitio_web      VARCHAR(200) NOT NULL DEFAULT '',
    logo           VARCHAR(200) NOT NULL DEFAULT '',   -- ruta del archivo
    ubicacion      GEOMETRY(Point, 4326),              -- x = longitud, y = latitud
    estado         VARCHAR(12)  NOT NULL DEFAULT 'borrador'
                   CHECK (estado IN ('borrador', 'publicado', 'suspendido')),
    -- Texto normalizado (minúsculas, sin tildes) para buscar
    busqueda       TEXT GENERATED ALWAYS AS (
                       lower(f_unaccent(nombre || ' ' || descripcion || ' ' || direccion))
                   ) STORED,
    creado_en      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    actualizado_en TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX negocio_ciudad_estado_idx ON negocio (ciudad_id, estado);
CREATE INDEX negocio_ubicacion_gix     ON negocio USING GIST (ubicacion);
CREATE INDEX negocio_busqueda_trgm_idx ON negocio USING GIN (busqueda gin_trgm_ops);

CREATE TRIGGER negocio_actualizado_trg
    BEFORE UPDATE ON negocio
    FOR EACH ROW EXECUTE FUNCTION set_actualizado_en();

-- Un negocio puede estar en varias categorías; una es la principal.
CREATE TABLE negocio_categoria (
    negocio_id   BIGINT  NOT NULL REFERENCES negocio(id)   ON DELETE CASCADE,
    categoria_id INTEGER NOT NULL REFERENCES categoria(id) ON DELETE RESTRICT,
    principal    BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (negocio_id, categoria_id)
);
CREATE INDEX negocio_categoria_cat_idx ON negocio_categoria (categoria_id);
CREATE UNIQUE INDEX negocio_categoria_principal_uq
    ON negocio_categoria (negocio_id) WHERE principal;

-- ---------------------------------------------------------------------
-- Promociones pagadas (exposición por período)
-- ---------------------------------------------------------------------
CREATE TABLE promocion (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    negocio_id  BIGINT       NOT NULL REFERENCES negocio(id) ON DELETE CASCADE,
    tipo        VARCHAR(20)  NOT NULL DEFAULT 'destacado'
                CHECK (tipo IN ('destacado', 'banner')),
    inicio      TIMESTAMPTZ  NOT NULL,
    fin         TIMESTAMPTZ  NOT NULL,
    monto_bs    NUMERIC(10,2) NOT NULL CHECK (monto_bs >= 0),
    estado      VARCHAR(12)  NOT NULL DEFAULT 'pendiente'
                CHECK (estado IN ('pendiente', 'pagada', 'cancelada')),
    referencia_pago VARCHAR(100) NOT NULL DEFAULT '',   -- comprobante, transferencia, QR
    notas       TEXT         NOT NULL DEFAULT '',
    creado_en   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CHECK (fin > inicio),
    -- Un negocio no puede tener dos promociones del mismo tipo con períodos que se solapan
    EXCLUDE USING GIST (
        negocio_id WITH =,
        tipo WITH =,
        tstzrange(inicio, fin) WITH &&
    ) WHERE (estado <> 'cancelada')
);
CREATE INDEX promocion_vigencia_idx ON promocion (tipo, estado, inicio, fin);

-- ---------------------------------------------------------------------
-- Eventos: visitas y acciones de contacto
-- ---------------------------------------------------------------------
CREATE TABLE evento (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    negocio_id   BIGINT      NOT NULL REFERENCES negocio(id) ON DELETE CASCADE,
    tipo         VARCHAR(20) NOT NULL CHECK (tipo IN (
                     'impresion',       -- apareció en un listado
                     'vista_ficha',     -- abrieron la ficha
                     'clic_llamar',
                     'clic_whatsapp',
                     'clic_web',
                     'clic_mapa')),
    promocion_id BIGINT      REFERENCES promocion(id) ON DELETE SET NULL,
    sesion       VARCHAR(64) NOT NULL DEFAULT '',  -- hash anónimo, nunca la IP
    creado_en    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX evento_negocio_fecha_idx ON evento (negocio_id, creado_en);
CREATE INDEX evento_tipo_fecha_idx    ON evento (tipo, creado_en);
CREATE INDEX evento_promocion_idx     ON evento (promocion_id) WHERE promocion_id IS NOT NULL;

-- ---------------------------------------------------------------------
-- Vistas de lectura
-- ---------------------------------------------------------------------

-- Listado público: solo publicados, con la marca de destacado vigente.
CREATE VIEW vw_negocio_listado AS
SELECT
    n.*,
    c.nombre         AS ciudad_nombre,
    p.id             AS promocion_id,
    (p.id IS NOT NULL) AS destacado,
    p.fin            AS destacado_hasta
FROM negocio n
JOIN ciudad c ON c.id = n.ciudad_id
LEFT JOIN LATERAL (
    SELECT id, fin
    FROM promocion
    WHERE negocio_id = n.id
      AND tipo   = 'destacado'
      AND estado = 'pagada'
      AND inicio <= now()
      AND fin    >  now()
    ORDER BY fin DESC
    LIMIT 1
) p ON TRUE
WHERE n.estado = 'publicado';

-- Métricas diarias por negocio, para reportes a quienes pagan.
CREATE VIEW vw_metricas_diarias AS
SELECT
    negocio_id,
    (creado_en AT TIME ZONE 'America/La_Paz')::date AS dia,
    tipo,
    count(*) AS total
FROM evento
GROUP BY negocio_id, dia, tipo;

